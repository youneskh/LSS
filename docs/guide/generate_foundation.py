class GuideDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            self.notify("TOCEntry", (level, text, self.page, key))


def _header_footer(canvas, doc):
    canvas.saveState()
    # Header
    canvas.setFont(BODY_FONT, 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(LEFT_M, PAGE_H - 1.3 * cm,
                      "Life Sciences Suite — Implementation & Operational Guide")
    canvas.drawRightString(PAGE_W - RIGHT_M, PAGE_H - 1.3 * cm,
                           "Foundation (Volume 0–1)")
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.4)
    canvas.line(LEFT_M, PAGE_H - 1.5 * cm, PAGE_W - RIGHT_M, PAGE_H - 1.5 * cm)
    # Footer
    canvas.drawString(LEFT_M, 1.2 * cm, "Odoo 19 Community · AGPL-3 · v1.0 (Draft)")
    canvas.drawRightString(PAGE_W - RIGHT_M, 1.2 * cm, "Page %d" % doc.page)
    canvas.line(LEFT_M, 1.5 * cm, PAGE_W - RIGHT_M, 1.5 * cm)
    canvas.restoreState()


