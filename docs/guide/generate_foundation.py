_bookmark_seq = 0


def _key(text):
    global _bookmark_seq
    _bookmark_seq += 1
    return "h_%s" % hashlib.md5((text + str(_bookmark_seq)).encode()).hexdigest()[:10]


def h1(text, story, level=0, kicker=None):
    """Major heading. Adds optional kicker line, accent rule, TOC bookmark."""
    key = _key(text)
    flow = []
    if kicker:
        flow.append(Paragraph(kicker.upper(), style_h1_kicker))
    p = Paragraph('<a name="%s"/>%s' % (key, text), style_h1)
    p.bookmark_name = text
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    flow.append(p)
    flow.append(HRFlowable(width="100%", thickness=1.2, color=ACCENT,
                           spaceBefore=2, spaceAfter=8))
    story.extend(flow)


def h2(text, story, level=1):
    key = _key(text)
    p = Paragraph('<a name="%s"/>%s' % (key, text), style_h2)
    p.bookmark_name = text
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    story.append(CondPageBreak(60))
    story.append(p)


def h3(text, story):
    story.append(CondPageBreak(40))
    story.append(Paragraph(text, style_h3))


def para(text, story, style=None):
    story.append(Paragraph(text, style or style_body))


def bullets(items, story, style=None):
    st = style or style_bullet
    for it in items:
        story.append(Paragraph(it, st, bulletText="•"))


def numbered(items, story):
    for i, it in enumerate(items, 1):
        story.append(Paragraph(it, style_bullet, bulletText="%d." % i))


def spacer(h, story):
    story.append(Spacer(1, h))


def badge(text, kind="verified"):
    """Inline truth-protocol badge as a small table cell."""
    bg = {"verified": BADGE_VERIFIED_BG, "custom": BADGE_CUSTOM_BG,
          "assumption": BADGE_ASSUMPTION_BG}[kind]
    fg = {"verified": BADGE_VERIFIED_FG, "custom": BADGE_CUSTOM_FG,
          "assumption": BADGE_ASSUMPTION_FG}[kind]
    st = ParagraphStyle("badge", fontName=HEAD_FONT_B, fontSize=7.5, leading=10,
                        textColor=fg, alignment=TA_CENTER)
    t = Table([[Paragraph(text, st)]], colWidths=[None])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), bg),
        ("BOX", (0, 0), (-1, -1), 0.5, fg),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]))
    return t


